#!/usr/bin/env python3
"""Regenerate the CJK fallback font used by the Panda UI.

The SquareLine fonts only carry the glyphs that existed when the screens were
exported, so any runtime text (ASR/TTS subtitles, toasts, WiFi state) can hit a
missing glyph.  This script builds a 16 px fallback font covering GB2312 and
the punctuation/ASCII ranges the UI mixes in.  The generated font is linked as
`ui_font_CJK16` and referenced from `.fallback` in the four SquareLine fonts.

Usage:
    python3 tools/fonts/gen_cjk_font.py [--bpp 4] [--size 16]
"""

import argparse
import pathlib
import re
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "panda_ai/components/panda_ui/generated/fonts/ui_font_CJK16.c"
FONT = (ROOT / "panda_ai/managed_components/lvgl__lvgl/scripts/built_in_font/"
        "SourceHanSansSC-Normal.otf")

# Ranges that are cheap and commonly mixed into Chinese copy.
EXTRA_RANGES = [
    (0x00A0, 0x00FF),  # Latin-1 supplement
    (0x2000, 0x206F),  # general punctuation: … — “ ” ‘ ’
    (0x2100, 0x214F),  # letterlike symbols: ℃ № ™
    (0x2190, 0x21FF),  # arrows
    (0x3000, 0x303F),  # CJK punctuation 。、「」
    (0xFF00, 0xFFEF),  # fullwidth forms ：；？！（）
]


def gb2312_chars():
    chars = set()
    for hi in range(0xA1, 0xFF):
        for lo in range(0xA1, 0xFF):
            try:
                chars.add(bytes([hi, lo]).decode("gb2312"))
            except UnicodeDecodeError:
                continue
    return chars


def build_charset():
    chars = {chr(cp) for cp in range(0x20, 0x7F)}
    for start, end in EXTRA_RANGES:
        chars.update(chr(cp) for cp in range(start, end + 1))
    chars.update(gb2312_chars())
    return "".join(sorted(chars))


def find_converter():
    exe = shutil.which("lv_font_conv")
    if exe:
        return [exe]
    for candidate in pathlib.Path.home().glob(".npm/_npx/*/node_modules/lv_font_conv/lv_font_conv.js"):
        node = shutil.which("node")
        if node:
            return [node, str(candidate)]
    sys.exit("lv_font_conv not found (install it or run via npx lv_font_conv)")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--size", type=int, default=16)
    parser.add_argument("--bpp", type=int, default=4)
    parser.add_argument("--font", type=pathlib.Path, default=FONT)
    parser.add_argument("--out", type=pathlib.Path, default=OUT)
    args = parser.parse_args()

    if not args.font.exists():
        sys.exit(f"font not found: {args.font}")

    symbols = build_charset()
    cmd = find_converter() + [
        "--font", str(args.font),
        "--size", str(args.size),
        "--bpp", str(args.bpp),
        "--format", "lvgl",
        "--no-compress",
        "--no-prefilter",
        "--no-kerning",
        "--symbols", symbols,
        "-o", str(args.out),
    ]
    print(f"generating {args.out.name}: {len(symbols)} symbols, "
          f"{args.size}px {args.bpp}bpp")
    subprocess.run(cmd, check=True)

    text = args.out.read_text(encoding="utf-8")
    text = re.sub(
        r"#ifdef LV_LVGL_H_INCLUDE_SIMPLE\n#include \"lvgl\.h\"\n#else\n"
        r"#include \"lvgl/lvgl\.h\"\n#endif\n",
        '#include "lvgl.h"\n',
        text,
    )
    # lv_font_conv 1.5.x still emits the LVGL 8 glyph cache, which LVGL 9
    # removed. Strip it so the font builds against the vendored LVGL 9.
    text = re.sub(
        r"#if LV_VERSION_CHECK\(8, 0, 0\)\n"
        r"/\*Store all the custom data of the font\*/\n"
        r"static\s+lv_font_fmt_txt_glyph_cache_t cache;\n"
        r"static const lv_font_fmt_txt_dsc_t font_dsc = \{\n"
        r"#else\n"
        r"static lv_font_fmt_txt_dsc_t font_dsc = \{\n"
        r"#endif\n",
        "static const lv_font_fmt_txt_dsc_t font_dsc = {\n",
        text,
    )
    text = re.sub(
        r"#if LV_VERSION_CHECK\(8, 0, 0\)\n"
        r"\s*\.cache = &cache\n"
        r"#endif\n",
        "",
        text,
    )
    header = (f"/* Regenerated by tools/fonts/gen_cjk_font.py from "
              f"{args.font.name}, {args.size}px {args.bpp}bpp. Do not edit. */\n")
    if "gen_cjk_font.py" not in text.splitlines()[0]:
        text = header + text
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out} ({args.out.stat().st_size / 1024:.0f} KiB)")


if __name__ == "__main__":
    main()
